  let lang = 'en';

  function t(key, params) {
    let s = (DICT[lang] && DICT[lang][key]);
    if (s == null) s = DICT.en[key];
    if (s == null) s = key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m));
    return s;
  }

  /** Resolve a localised value: {en,ku} | string | number. */
  function L(v) {
    if (v == null) return '';
    if (typeof v === 'string' || typeof v === 'number') return String(v);
    if (typeof v === 'object') {
      const s = v[lang] != null && v[lang] !== '' ? v[lang] : (v.en != null ? v.en : Object.values(v)[0]);
      return s == null ? '' : String(s);
    }
    return '';
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  }

  function setLang(l) {
    lang = l === 'ku' ? 'ku' : 'en';
    const html = document.documentElement;
    html.lang = lang === 'ku' ? 'ckb' : 'en';
    html.dir = lang === 'ku' ? 'rtl' : 'ltr';
    apply();
  }

  const nf = new Intl.NumberFormat('en-US');
  window.I18N = { t, L, setLang, apply, getLang: () => lang, num: n => nf.format(n) };
